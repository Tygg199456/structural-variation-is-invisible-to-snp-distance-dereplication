#!/usr/bin/env python3
"""Generate docs/NUMBER_REGISTRY.md from results/numbers.json.

Every analysis script appends one JSON object per run to results/numbers.json.
This turns the newest value of each key into the manuscript-facing registry:
manuscript location -> quantity -> value -> producing script -> how it was computed.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NUM = os.path.join(ROOT, "results", "numbers.json")
OUT = os.path.join(ROOT, "docs", "NUMBER_REGISTRY.md")

SECTION = {
 "sets": ("Methods 2.1 / Table 1b",
          "results/qc/deletion_profile_all.tsv, tierA_refined.tsv, tierB_candidates.tsv; results/dedup/sites_tier*.tsv",
          "row counts"),
 "noise_floor": ("Results 3.1 / Fig. 2",
          "results/snippy/GCF_000009065.1/snps.aligned.fa; results/dedup/snp_distance_raw_tierB.npy",
          "maximal [Nn-] runs (reported per denominator: chromosome vs all four replicons); pairwise differences over jointly called sites"),
 "quality_metrics": ("Results 3.2 / Fig. 3",
          "results/figures/fig2a_metric_flags.csv, fig2d_checkm.csv",
          "flagged = value below the threshold (CheckM 98 %, aligned bases 95 %, called fraction 0.859); reference itself excluded from reference-relative metrics"),
 "archive_composition": ("Results 3.2, 3.8 / Table 4a",
          "results/qc/variant_freq_strata.tsv, replicon_three_state_seqreport.tsv",
          "frequencies by set; plasmid submission read from the submitted sequence inventory"),
 "spatial": ("Results 3.3 / Fig. 4",
          "results/figures/fig3b_recurrence.csv; results/qc/uncalled_blocks_all.tsv",
          "5 kb-binned uncalled blocks reaching 10 kb"),
 "polarity": ("Results 3.5, 3.6 / Fig. 6 / Table 2",
          "results/figures/fig5a_region_polarity.csv, fig5b_background.csv, fig5b_block_delta.csv",
          "outgroup callable fractions; percentile rank against 1,000 random 25 kb windows (quantiles: linearly interpolated order statistics)"),
 "dereplication": ("Results 3.4 / Fig. 5 / Table 5",
          "results/dedup/tierA_clusters.*.tsv; results/qc/dedup_modes_summary.txt, dedup_mixed_classification.tsv",
          "complete-linkage hierarchical clustering at t = 20; four deletion-profile constraints"),
 "cluster_419": ("Results 3.7",
          "results/figures/fig1d_cluster_internal.csv, fig1d_cluster_years.csv",
          "within-cluster pairwise distances of the 419-genome set"),
 "directionality": ("Results 3.8 / Table 4b",
          "results/qc/deletion_profile_all.tsv, assembly_metadata.tsv, replicon_three_state_seqreport.tsv",
          "two-sided Fisher exact test; Wilson intervals"),
 "pseudogene_entanglement": ("Results 4.8 / Table S6",
          "results/qc/pseudogene_entanglement.tsv",
          "curated CO92 pseudogenes against the automated annotation"),
}


def fmt(v):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, dict):
        return "; ".join("%s = %s" % (k, fmt(x)) for k, x in v.items())
    return str(v)


def main():
    latest = {}
    for line in open(NUM):
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        for k, v in rec["numbers"].items():
            latest[k] = (v, rec["script"], rec["ts"])      # newest wins
    L = ["# Number registry", "",
         "Every quantity the manuscript's Results reports, with the value produced by the",
         "archived code, the script that produced it and the computation behind it.",
         "Generated by `scripts/make_number_registry.py` from `results/numbers.json`, which",
         "each analysis script appends to; regenerate the values with",
         "`python3 scripts/audit_numbers.py`.", "",
         "| manuscript | quantity | value | produced by | computed from |",
         "|---|---|---|---|---|"]
    for k, (v, script, ts) in sorted(latest.items()):
        sec, files, how = SECTION.get(k, ("-", "-", "-"))
        L.append("| %s | `%s` | %s | `%s` | %s |" % (sec, k, fmt(v), script, how))
    L += ["", "## What is deliberately not in this registry", "",
          "Values quoted from published literature, or read directly from NCBI metadata",
          "(accession, collection date, assembly level), are not derived here; the",
          "manuscript cites them to their source. Every number that the manuscript derives",
          "itself must be traceable to a file and a line — that rule is why this file",
          "exists.", ""]
    open(OUT, "w").write("\n".join(L))
    print("wrote %s (%d quantities)" % (os.path.relpath(OUT, ROOT), len(latest)))


if __name__ == "__main__":
    main()
